# 各列に意味のある名前を順番通りに割り当てる。
# （元データの列順と完全に一致させる必要があるので順序厳守）
# =============================================================
COLUMNS = [
    "year", "month", "day", "kaiji", "place", "nichiji", "race_no",
    "race_name", "class_code", "surface", "track_code", "distance",
    "track_condition", "horse_name", "sex", "age", "jockey_name",
    "weight_carried", "field_size", "horse_no", "finish_pos",
    "goal_pos", "abnormal_code", "margin_time", "popularity",
    "finish_time", "finish_clock", "adj_time",
    "corner1", "corner2", "corner3", "corner4",
    "last3f_time", "horse_weight", "trainer_name", "affiliation",
    "prize", "ped_id", "jockey_code", "trainer_code", "race_id",
    # --- 42〜45 を追加 ---
    "blank1", "blank2", "blank3",   # 42〜44: 生成されるが中身は空
    "pci",                          # 45: PCI（ペース指数）
]   # ← ★問題1の修正：リストを ] で閉じる


# =============================================================
# トラックコードの変換テーブル
# トラックコードは1つの数値に「路面・障害有無・外回り」という
# 複数の情報が畳み込まれているため、個別のフラグに分解できるよう
# コードごとの意味を辞書で定義しておく。
#   surface_track : 路面（芝 or ダート）
#   is_jump       : 障害競走かどうか（1=障害）
#   is_outer      : 外回りコースかどうか（1=外回り）
# =============================================================
TRACK_CODE_MAP = {
    0: {"surface_track": "芝",     "is_jump": 0, "is_outer": 0},  # 芝（通常）
    1: {"surface_track": "ダート", "is_jump": 0, "is_outer": 0},  # ダート
    2: {"surface_track": "芝",     "is_jump": 1, "is_outer": 0},  # 障害・芝
    3: {"surface_track": "ダート", "is_jump": 1, "is_outer": 0},  # 障害・ダート
    8: {"surface_track": "芝",     "is_jump": 0, "is_outer": 1},  # 芝・外回り
}


# =============================================================
# クラスコード → レースの格の序列（0〜13）への変換テーブル
# クラスコードの数値そのものは等間隔ではない（7, 11, 15, 19…）ため、
# 「格の上下関係」を正しく表す連続した序列（順序尺度）に変換する。
# 数値が大きいほど格上（未出走=0 … G1=13）になるよう設計。
# =============================================================
CLASS_LEVEL_MAP = {
    11: 0,   # 未出走
    15: 1,   # 新馬
    7:  2,   # 未勝利
    19: 3,   # 400万下（1勝クラス）
    23: 4,   # 500万下
    39: 5,   # 900万下
    43: 6,   # 1000万下（2勝クラス相当）
    63: 7,   # 1500万下
    67: 8,   # 1600万下（3勝クラス相当）
    131: 9,  # オープン（重賞以外）
    147: 10, # 重賞（グレードなし）
    163: 11, # G3
    179: 12, # G2
    195: 13, # G1
}


def load_csv(path: str) -> pd.DataFrame:
    """CSVを読み込み、カラム名の付与と開催日（日付型）の生成を行う"""
    # ------------------------------------------------------------
    # CSVを読み込む。
    #   names=COLUMNS  : ヘッダーが無いので自前のカラム名を割り当てる
    #   header=None    : 1行目をヘッダーとして扱わない（データとして読む）
    #   dtype=str      : 一旦すべて文字列で読み込む（数値の自動変換による
    #                    欠損・型崩れを防ぎ、後で明示的に型変換するため）
    #   encoding=cp932 : 日本語（馬名・騎手名等）がShift-JIS系のため指定
    # ------------------------------------------------------------
    df = pd.read_csv(path, names=COLUMNS, header=None,
                     dtype=str, encoding="cp932")

    # ------------------------------------------------------------
    # 「年」は西暦下2桁しか無いため、4桁の西暦に復元する。
    # 例：23 → 2023、98 → 1998
    # 1985年からのデータしかないため、ここでは「50以下なら2000年代、
    # 51以上なら1900年代」と仮定している。
    # ------------------------------------------------------------
    df["year_full"] = df["year"].astype(int).apply(
        lambda y: 2000 + y if y <= 50 else 1900 + y
    )

    # ------------------------------------------------------------
    # 年・月・日を結合して「開催日」をdatetime型で生成する。
    # 時系列分割や過去成績の集計で「日付」を使うため必須の前処理。
    #   errors="coerce" : 不正な日付（存在しない日付等）はNaT（欠損）にする
    # ------------------------------------------------------------
    df["race_date"] = pd.to_datetime(
        dict(year=df["year_full"],
             month=df["month"].astype(int),
             day=df["day"].astype(int)),
        errors="coerce",
    )
    return df


def clean_dtypes(df: pd.DataFrame) -> pd.DataFrame:
    """文字列で読み込んだ各列を適切なデータ型に変換し、クレンジングする

    　　元の整数変換・float変換・strip処理に加え、
     　 PCI変換・走破時計変換・空カラム削除をここにまとめる
    """
    # ------------------------------------------------------------
    # 整数として扱うべき列を数値型に変換する。
    #   errors="coerce" : 数値に変換できない値（空文字・記号等）はNaNにする
    # 着順や人気順など、計算・比較に使う列を数値化しておく。
    # ------------------------------------------------------------
    int_cols = ["distance", "age", "field_size", "horse_no",
                "finish_pos", "goal_pos", "popularity", "class_code",
                "abnormal_code"]
    for col in int_cols:
        df[col] = pd.to_numeric(df[col], errors="coerce")

    # ------------------------------------------------------------
    # 小数を含む列を浮動小数点型に変換する。
    # 斤量・タイム・馬体重・賞金など、小数や大きな数値を扱う列。
    # ------------------------------------------------------------
    float_cols = ["weight_carried", "margin_time", "finish_time",
                  "adj_time", "last3f_time", "horse_weight", "prize"]
    for col in float_cols:
        df[col] = pd.to_numeric(df[col], errors="coerce")

    # ------------------------------------------------------------
    # 各コーナーの通過順位を数値型に変換する。
    # レース展開（先行/差し等）を分析する際の材料になる。
    # ------------------------------------------------------------
    for c in ["corner1", "corner2", "corner3", "corner4"]:
        df[c] = pd.to_numeric(df[c], errors="coerce")

    # ------------------------------------------------------------
    # PCI（ペース指数）を数値型に変換する。
    # レース後に算出される指標なので、当該レースの特徴量には使わず、
    # 過去レースの集計値（past_avg_pci）としてのみ利用する（リーク防止）。
    # ------------------------------------------------------------
    df["pci"] = pd.to_numeric(df["pci"], errors="coerce")

    # ------------------------------------------------------------
    # 走破時計（4桁文字列）を秒に変換する。
    # 形式: 分1桁 + 秒2桁 + 1/10秒1桁
    # 例: "1145" → 1分14秒5 → 60 + 14 + 0.5 = 74.5 秒
    # 入線していない場合は "----" なので、その場合はNaNにする。
    # （走破時計もレース結果なので、当該レースの特徴量には使わない）
    # ------------------------------------------------------------
    def clock_to_sec(s):
        # 欠損や未入線("----")は秒に変換できないためNaNを返す
        if pd.isna(s) or str(s) in ("----", ""):
            return np.nan
        s = str(s).zfill(4)          # 4桁に0埋め（不足桁を補う）
        minutes = int(s[0])          # 1桁目：分
        seconds = int(s[1:3])        # 2〜3桁目：秒
        tenths = int(s[3])           # 4桁目：1/10秒
        return minutes * 60 + seconds + tenths / 10

    df["finish_clock_sec"] = df["finish_clock"].apply(clock_to_sec)

    # ------------------------------------------------------------
    # 文字列項目の前後の空白を除去する。
    # 名前やコード類は、余分な空白があると同じ値でも別物と判定され、
    # グループ集計やエンコーディングで不整合を起こすため正規化する。
    # ------------------------------------------------------------
    for col in ["jockey_name", "trainer_name", "horse_name",
                "place", "surface", "track_condition", "affiliation"]:
        df[col] = df[col].astype(str).str.strip()

    # ------------------------------------------------------------
    # 42〜44の空カラムは中身が無いため削除する。
    # 以降の処理で誤って特徴量に混入するのを防ぎ、データも軽くする。
    # ------------------------------------------------------------
    df = df.drop(columns=["blank1", "blank2", "blank3"], errors="ignore")

    return df


def add_track_features(df: pd.DataFrame) -> pd.DataFrame:
    """トラックコードを路面・障害・外回りの個別フラグに分解する"""
    # ------------------------------------------------------------
    # トラックコードを数値型に変換する（マッピングのキーと揃えるため）。
    # ------------------------------------------------------------
    df["track_code"] = pd.to_numeric(df["track_code"], errors="coerce")

    # ------------------------------------------------------------
    # TRACK_CODE_MAP を使ってトラックコードを辞書に変換し、
    # その辞書を複数列に展開する（1列 → 3列の情報へ分解）。
    #   .map(TRACK_CODE_MAP)  : コード値を辞書に置き換える
    #   .apply(pd.Series)     : 辞書を列ごとに展開してDataFrame化する
    # ------------------------------------------------------------
    track_df = df["track_code"].map(TRACK_CODE_MAP).apply(pd.Series)

    # ------------------------------------------------------------
    # 展開した情報を元のDataFrameの列として追加する。
    #   surface_from_track : トラックコード由来の路面情報
    #   is_jump            : 障害競走フラグ（後で障害を除外するのに使う）
    #   is_outer           : 外回りフラグ（欠損は0=外回りでないとして補完）
    # ------------------------------------------------------------
    df["surface_from_track"] = track_df["surface_track"]
    df["is_jump"] = track_df["is_jump"].fillna(0).astype(int)
    df["is_outer"] = track_df["is_outer"].fillna(0).astype(int)

    # ------------------------------------------------------------
    # 芝かダートかを0/1のフラグにする（芝=1）。
    # モデルが扱いやすいよう、路面を数値フラグとして明示化する。
    # ------------------------------------------------------------
    df["is_turf"] = df["surface_from_track"].eq("芝").astype(int)

    return df



"""Step 4: 異常コードの分類・フラグ化を行うモジュール。

異常コードの扱いを「含める／含めない」の比較実験の起点となる処理。
ここで作るフラグは、除外判定・目的変数作成・過去履歴の集計にのみ使い、
当該レースの特徴量には絶対に使わない（走る前には分からない情報のため）。

異常コードの値の意味：
    0 : 正常（完走）
    1 : 出走取消
    2 : 発走除外
    3 : 競走除外
    4 : 競走中止
    5 : 失格
    6 : 落馬再騎乗
    7 : 降着
"""

def classify_abnormal(df: pd.DataFrame) -> pd.DataFrame:
    """異常コードを意味ごとに分類し、各種フラグを生成する。

    Parameters
    ----------
    df : pd.DataFrame
        abnormal_code 列を含む前処理途中のデータ。

    Returns
    -------
    pd.DataFrame
        異常コード由来のフラグ列を追加したデータ。
    """
    # ------------------------------------------------------------
    # 異常コードの欠損を0（正常）として扱う。
    # 元データで異常が無い場合に空欄になっていることがあるため、欠損＝異常なし＝正常完走(0) とみなして補完する。
    # ------------------------------------------------------------
    code = df["abnormal_code"].fillna(0)

    # ------------------------------------------------------------
    # 【正常完走フラグ】異常コード0（正常）を1とする。
    # 無事にレースを走り切り、着順が正常に確定した記録を表す。
    # 後続処理で「正常な記録かどうか」を判定する基準になる。
    # ------------------------------------------------------------
    df["is_normal"] = code.eq(0).astype(int)

    # ------------------------------------------------------------
    # 【出走取消・除外フラグ】そもそもレースを走っていない記録。
    #   1 : 出走取消（レース前に出走をやめた）
    #   2 : 発走除外（競走除外の旧式名称）
    #   3 : 競走除外（競走から除外された）
    # これらは馬券が返還される対象であり、「走った馬」ではない。
    # ------------------------------------------------------------
    df["is_scratched"] = code.isin([1, 2, 3]).astype(int)

    # ------------------------------------------------------------
    # 【競走中止フラグ】発走後にゴールへ到達できずレースを
    # 途中でやめた記録。
    #   4 : 競走中止
    # ゲートは出て走り始めたが完走しなかったケース。
    # ------------------------------------------------------------
    df["is_dnf"] = code.isin([4]).astype(int)

    # ------------------------------------------------------------
    # 【失格・降着フラグ】走ったものの順位が無効化/降格された記録。
    #   5 : 失格（着順が取り消される）
    #   6 : 落馬再騎乗（落馬後に乗り直したケース）
    #   7 : 降着（審議で着順が下げられた）
    # 走ってはいるが正常な着順とは扱えないケース。
    # ------------------------------------------------------------
    df["is_disqualified"] = code.isin([5, 6, 7]).astype(int)

    # ------------------------------------------------------------
    # 【出走したかフラグ】実際にゲートを出て走ったかどうか。
    # 取消・除外（1,2,3）以外はすべて「走った」とみなす。
    #   ~code.isin([1, 2, 3]) : 取消・除外でなければ True
    # includeパターンで「走った馬」を残す絞り込みに使う。
    # （競走中止・失格・降着・正常完走が含まれる）
    # ------------------------------------------------------------
    df["did_run"] = (~code.isin([1, 2, 3])).astype(int)

    # ------------------------------------------------------------
    # 【有効着順フラグ】完走して着順が有効に確定しているか。
    # 以下の3条件をすべて満たす場合のみ1とする：
    #   code.eq(0)                : 異常コードが正常(0)
    #   finish_pos.notna()        : 着順が欠損していない
    #   finish_pos > 0            : 着順が正の値（0や負は無効）
    # 過去成績の集計や目的変数の作成で、
    # 「信頼できる着順」だけを使うための基準になる。
    # ------------------------------------------------------------
    df["has_valid_finish"] = (
        code.eq(0)
        & df["finish_pos"].notna()
        & (df["finish_pos"] > 0)
    ).astype(int)

    return df

#障害競走と出走頭数が少なすぎるレースを除外する絞り込みを行う
def filter_records(df: pd.DataFrame) -> pd.DataFrame:
    """障害・頭数のみで絞り込み。異常記録はこの段階では残す"""
    # 障害競走を除外
    df = df[~df["track_code"].isin([2, 3])]
    # 出走頭数が少ないレースを除外
    df = df[df["field_size"] >= 5]
    return df.reset_index(drop=True)


#レース条件・クラス特徴量の生成
def add_race_features(df: pd.DataFrame) -> pd.DataFrame:
    """レース前に既知の条件を、予測に使いやすい特徴量へ変換する"""
    # ------------------------------------------------------------
    # 距離を4つのカテゴリ（短距離〜長距離）に区分する。
    # 距離は連続値だが、競馬では「短距離向き／長距離向き」といった適性がカテゴリ的に効くため、区分することで解釈もしやすくなる。
    #   bins=[0,1400,1800,2200,4000] : 区切りの境界値（m）
    #       〜1400m   : sprint（短距離）
    #       〜1800m   : mile  （マイル）
    #       〜2200m   : middle（中距離）
    #       〜4000m   : long  （長距離）
    # ------------------------------------------------------------
    df["dist_category"] = pd.cut(
        df["distance"],
        bins=[0, 1400, 1800, 2200, 4000],
        labels=["sprint", "mile", "middle", "long"],
    )

    # ------------------------------------------------------------
    # 馬番を頭数で割り、枠の内外を「相対位置」として表す。
    # 単純な馬番（1〜18）は頭数によって内外の意味が変わる（例：8番は8頭立てなら大外だが18頭立てなら真ん中）。
    #頭数で割ることでどのレースでも「0に近い＝内、1に近い＝外」と統一的に扱える。
    # ------------------------------------------------------------
    df["draw_ratio"] = df["horse_no"] / df["field_size"]

    # ------------------------------------------------------------
    # 斤量（背負う総重量）を馬体重で割り、「馬に対する負担の重さ」を表す。
    # 同じ斤量でも、小柄な馬には重く大柄な馬には軽いため、馬体重との比をとることで負担度を相対的に評価できる。
    # ------------------------------------------------------------
    df["weight_ratio"] = df["weight_carried"] / df["horse_weight"]

    return df


def add_class_features(df: pd.DataFrame) -> pd.DataFrame:
    """クラスコードを順序尺度や各種フラグに変換する"""
    # ------------------------------------------------------------
    # クラスコード（7,11,15…195）を格の序列（0〜13）に変換する。
    # コードの数値自体は等間隔でないため、CLASS_LEVEL_MAP を使って「格の高さ」を正しく表す連続した序列に置き換える。
    # 数値が大きいほど格上（未出走=0 … G1=13）。
    # ------------------------------------------------------------
    df["class_level"] = df["class_code"].map(CLASS_LEVEL_MAP)

    # ------------------------------------------------------------
    # 重賞（重賞・G3・G2・G1 = 序列10以上）かどうかのフラグを作る。
    # 重賞はメンバーのレベルが高く、傾向が条件戦と異なるため、まとめて識別できるフラグが有用だと考える。
    # ------------------------------------------------------------
    df["is_graded"] = df["class_level"].ge(10).astype(int)

    # ------------------------------------------------------------
    # 最高格であるG1かどうかのフラグ（クラスコード195）。
    # G1は特にレベルが突出しているため単独で区別できるようにする。
    # ------------------------------------------------------------
    df["is_g1"] = df["class_code"].eq(195).astype(int)

    # ------------------------------------------------------------
    # 未勝利・未出走・新馬（クラスコード7,11,15）のフラグ。
    # これらはキャリアの浅い馬が集まり、過去成績が乏しいレースなので、
    # 他のクラスと区別して扱えるようにする。
    # ------------------------------------------------------------
    df["is_maiden"] = df["class_code"].isin([7, 11, 15]).astype(int)

    return df

#欠損値処理を行う
def handle_missing(df: pd.DataFrame) -> pd.DataFrame:
    """欠損値を処理する。欠損を単純に埋めるだけでなく、
    「欠損していた」という事実自体も情報として残す方針で扱う"""
    # ------------------------------------------------------------
    # 馬体重が欠損していたかどうかを示すフラグを先に作る。
    # 欠損を補完してしまうと「元々欠損だった」情報が失われるため、補完する前にフラグ化しておく（欠損自体に意味がある場合に備える）。
    # ------------------------------------------------------------
    df["horse_weight_missing"] = df["horse_weight"].isna().astype(int)

    # ------------------------------------------------------------
    # 馬体重の欠損を、同じ馬（血統登録番号ごと）の中央値で補完する。
    # 同一馬の馬体重は近い値になりやすいため、その馬自身の過去・前後の記録から推定する方が、全体平均で埋めるより妥当性が高い。
    #   groupby("ped_id") : 馬ごとにグループ化
    #   transform(...)    : 各馬の中央値でその馬の欠損を埋める
    # ------------------------------------------------------------
    df["horse_weight"] = df.groupby("ped_id")["horse_weight"].transform(
        lambda s: s.fillna(s.median())
    )

    # ------------------------------------------------------------
    # それでも埋まらない欠損（その馬の記録が1件も無い等）は、データ全体の中央値で最終的に補完する。
    # これにより馬体重列に欠損が残らないことを保証する。
    # ------------------------------------------------------------
    df["horse_weight"] = df["horse_weight"].fillna(df["horse_weight"].median())

    # ------------------------------------------------------------
    # 人気順の欠損フラグを作る。
    # 人気順は通常すべての出走馬に付くが、出走取消・除外馬などでは欠損する可能性がある。その「欠損していた」状態を情報として残す。
    # （人気順そのものは市場予測なので、特徴量として使う際は扱い注意）
    # ------------------------------------------------------------
    df["popularity_missing"] = df["popularity"].isna().astype(int)

    return df